export function getPoemsByDynasty(dynastyId: string): Poem[] {
  return poems.filter(poem => poem.dynasty === dynastyId)
}

export function getPoemById(id: number): Poem | undefined {
  return poems.find(poem => poem.id === id)
}

export function getDynastyById(id: string): Dynasty | undefined {
  return dynasties.find(dynasty => dynasty.id === id)
}
